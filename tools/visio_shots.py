def _builder_identity(builder: Path) -> dict[str, str]:
    """The case module a run built from: where it is, and its content's hash.

    The hash is what names it. A builder outside this repository is not
    covered by the commit or the dirty check, and two edits of one file are
    two builders.
    """
    path = builder.resolve()
    shown = str(path.relative_to(_REPO)) if path.is_relative_to(_REPO) else str(builder)
    return {"path": shown, "sha256": _sha256(path.read_bytes())}


def _source_identity(builder: Path) -> dict:
    """The code a run builds from: taken before the build, since the tree can change during a long export."""
    return {
        "commit": _git(_REPO, "rev-parse", "HEAD"),
        "branch": _git(_REPO, "branch", "--show-current") or "(detached)",
        "dirty": bool(_git(_REPO, "status", "--porcelain", "--", "src", "tools", "tests")),
        "builder": _builder_identity(builder),
    }


def _jobs(
    candidate_dir: Path, cases: list[_Case], ref_dir: Path, ref_cases: dict[str, _Case]
) -> list[tuple[str, _Case, Path]]:
    """Every (variant, case, file) to photograph: each case's `.before` file where it has one, the ref's build, the candidate's.

    The `.before` file is photographed with the candidate's case, whose
    triggers name shapes the fixture already has (a trigger naming a shape
    the case created is skipped by the export). The ref's build is
    photographed with the case the ref's own build wrote: its library may
    have given a shape the case created another ID.
    """
    jobs = []
    for case in cases:
        before = candidate_dir / f"{case.file_stem}.before.vsdx"
        if before.exists():
            jobs.append(("before", case, before))
        if case.stem in ref_cases:
            jobs.append(("ref", ref_cases[case.stem], ref_dir / f"{case.file_stem}.vsdx"))
        jobs.append(("candidate", case, candidate_dir / f"{case.file_stem}.vsdx"))
    return jobs


def _command_run(builder: Path, against: str | None, store: Path, dpi: int) -> int:
    sys.path.insert(0, str(_TOOLS))
    import visio_verify

    now = datetime.datetime.now(datetime.timezone.utc)
    source = _source_identity(builder)
    with tempfile.TemporaryDirectory(prefix="visio-shots-") as scratch:
        work = Path(scratch)
        candidate = work / "candidate"
        errors = {"candidate": _build(builder, _REPO / "src", candidate)}
        ref_info, ref_cases = None, {}
        if against:
            ref_src, commit = _export_library(_REPO, against, work / "ref-library")
            errors["ref"] = _build(builder, ref_src, work / "ref")
            ref_info = {"ref": against, "commit": commit}
            ref_cases = {case.stem: case for case in _read_cases(work / "ref")}
        cases = _read_cases(candidate)
        if not cases:
            print(f"{builder.name} built no cases: {errors['candidate']}", file=sys.stderr)
            return 2
        try:
            visio, shots = _shoot(_jobs(candidate, cases, work / "ref", ref_cases), dpi, work / "shots")
        except visio_verify.VisioUnavailable as error:
            print(f"Visio is not usable from here: {error}", file=sys.stderr)
            return 2
    run_id = f"{now:%Y%m%dT%H%M%SZ}_{source['commit'][:7]}"
    identity = {"run": run_id, "created": now.isoformat(timespec="seconds"), **source}
    identity |= {"against": ref_info, "visio": visio, "dpi": dpi}
    manifest = _record_run(store, identity, {case.stem: case.line for case in cases}, shots, build_errors=errors)
    print(_summary(manifest).split("\n## ")[0])
    recorded = manifest["run"]
    print(f"recorded {store / 'runs' / recorded}; images in {store / 'local' / recorded / 'report.html'}")
    return 1 if _failures(manifest) else 0


def main(argv: list[str] | None = None) -> int:
    """Run the harness; 0 when every candidate case was judged and none is stale on open, 1 otherwise, 2 when it could not run."""
    parser = argparse.ArgumentParser(prog="visio_shots.py", description=__doc__.split("\n\n")[0])
    commands = parser.add_subparsers(dest="command", required=True)
    run = commands.add_parser("run", help="build, photograph and record the case set")
    run.add_argument("--against", help="a git ref whose library builds the comparison column, e.g. main")
    run.add_argument("--builder", type=Path, default=_BUILDER, help="the case module (default: tools/writes_land_cases.py)")
    run.add_argument("--store", type=Path, default=_STORE, help="where runs are recorded (default: .hermes/visio-shots)")
    run.add_argument("--dpi", type=int, default=150, help="PNG resolution (default: 150)")
    diff = commands.add_parser("diff-runs", help="what changed between two recorded runs")
    diff.add_argument("first")
    diff.add_argument("second")
    diff.add_argument("--store", type=Path, default=_STORE)
    args = parser.parse_args(argv)

    if args.command == "diff-runs":
        lines = _diff_runs(args.store, args.first, args.second)
        print("\n".join(lines) if lines else f"no case is drawn differently between {args.first} and {args.second}")
        return 0
    try:
        return _command_run(args.builder.resolve(), args.against, args.store, args.dpi)
    except BuildFailed as error:
        print(error, file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
