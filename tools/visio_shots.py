"""Photograph what Visio draws for a case set, compare it, and keep a record of every run.

Usage:
    python tools/visio_shots.py run [--against REF] [--builder PATH] [--store DIR] [--dpi N]
    python tools/visio_shots.py diff-runs <run-a> <run-b> [--store DIR]

``run`` builds the case set twice when ``--against`` names a git ref: once
with this working tree's library (the candidate) and once with that ref's,
exported with ``git archive`` (the ref). The builder is
``tools/writes_land_cases.py`` unless ``--builder`` names another module that
keeps its contract: ``CASES``, callables that each write one case into a
folder and return it, and ``as_json``, which turns them into
``expected.json``. A case the ref's library cannot build is recorded, and
the rest still run.

A Windows Visio (``tools/visio_export.ps1``) exports each case's page as PNG
and SVG as it opens, then again after ``Cell.Trigger()`` recalculates every
cell the case checks. It does this for the candidate, the ref and the
untouched fixture (``<case>.before.vsdx``). The SVG names each shape by its
Visio ID and carries its position, path, text and style, so two exports are
compared shape by shape, exactly. No pixels are compared and no text is
recognised.

Visio draws from the values a file caches, so a candidate drawn differently
after recalculating was stale on open: the file said one thing and would
show another as soon as anything recalculated (#461). ``run`` exits 1 when
any case is, and when any candidate case was never judged because it could
not be built or exported. Differences from the ref or from the fixture are what the
change did, and are reported, not judged.

Every run is recorded in the store (``.hermes/visio-shots`` by default):
``runs/<run>/manifest.json`` and ``summary.md``, each SVG once under
``objects/`` by its hash, and one line in ``index.jsonl``. All of that is
text and is committed. The PNGs and a self-contained ``report.html`` go under
``local/``, which git ignores. ``diff-runs`` lists the cases whose candidate
drawing or verdict changed between two recorded runs.
"""

